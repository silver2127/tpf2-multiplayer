enum class EntityRegister { Rbx, R12, R15 };
enum class SeedIntermediate { Rax, Rdx, MixedRdx };
struct PersonSeedSite {
    uintptr_t windowRva, returnRva;
    uint32_t tag;
    EntityRegister entity;
    SeedIntermediate intermediate;
    const unsigned char* bytes;
    size_t size;
};
#include "person_seed_sites_linux.h"
constexpr PersonSeedSite kIdlePersonSeedSite{
    kIdleSeedWindowRva, kIdleSeedReturnRva, 9, EntityRegister::R15,
    SeedIntermediate::MixedRdx, kIdleSeedCallBytes, sizeof(kIdleSeedCallBytes)
};
struct PersonSeedRegisters {
    uint64_t rdx, rax;
    uintptr_t rbx, r12, r15, caller;
};
static_assert(sizeof(PersonSeedRegisters) == 48);
static_assert(offsetof(PersonSeedRegisters, caller) == 40);

using ExclusiveRandom = int (*)(void*, int, int);
using InclusiveRandom = int (*)(void*, const int*);
void* g_originalRandom = nullptr;
InclusiveRandom g_nativeInclusive = nullptr;
using PersonMt = void (*)(void*, uint32_t);
void* g_originalPersonMt = nullptr;
uintptr_t g_departureSeedReturn = 0;
uintptr_t g_arrivalSeedReturn = 0;
uintptr_t g_idleSeedReturn = 0;
uintptr_t g_personImageBase = 0;

uint32_t NativeNext(void* engine)
{
    const int bounds[] = {INT_MIN, INT_MAX};
    // The native full-range path yields raw + INT_MIN with machine wrapping.
    // Convert back with unsigned subtraction, never overflowing signed C++.
    return uint32_t(g_nativeInclusive(engine, bounds)) - uint32_t(INT_MIN);
}

__attribute__((noinline)) int DestinationRandom(void* engine, int minimum, int maximum)
{
    // This overload has one interval-conversion contract for every caller.
    // Its Windows counterpart uses modulo/rejection for all valid ranges.
    if (minimum < maximum) {
        return Tpf2mpWindowsUniformIntInclusive(minimum, maximum - 1, engine, NativeNext);
    }
    // Also preserve the native assertion path for any invalid exclusive range.
    return reinterpret_cast<ExclusiveRandom>(g_originalRandom)(engine, minimum, maximum);
}

uint32_t SeedFromRegisters(const PersonSeedSite& site, const PersonSeedRegisters& registers)
{
    const uintptr_t address = site.entity == EntityRegister::Rbx ? registers.rbx
        : site.entity == EntityRegister::R12 ? registers.r12 : registers.r15;
    uint32_t entity;
    std::memcpy(&entity, reinterpret_cast<const void*>(address), sizeof(entity));
    const uint64_t intermediate = site.intermediate == SeedIntermediate::Rax
        ? registers.rax : registers.rdx;
    return Tpf2mpWindowsEntitySeedFromNative(site.tag, intermediate, entity,
                                           site.intermediate == SeedIntermediate::MixedRdx);
}
