// Capture registers before the original constructor or C++ can overwrite them.
// Only an exact, verified caller may interpret an entity pointer. The original
// return address is explicitly recorded after the five register snapshots.
extern "C" __attribute__((visibility("hidden"), noinline))
void Tpf2mpPersonSeedDispatch(void* engine, uint32_t seed, const PersonSeedRegisters* registers)
{
    const uintptr_t caller = registers->caller;
    if (caller == g_departureSeedReturn) {
        seed = Tpf2mpWindowsDepartureSeed(seed);
    } else if (caller == g_arrivalSeedReturn) {
        seed = Tpf2mpWindowsArrivalSeed(seed);
    } else if (caller == g_idleSeedReturn) {
        seed = SeedFromRegisters(kIdlePersonSeedSite, *registers);
    } else {
        for (const auto& site : kExtraPersonSeedSites) {
            if (caller == g_personImageBase + site.returnRva) {
                seed = SeedFromRegisters(site, *registers);
                break;
            }
        }
    }
    reinterpret_cast<PersonMt>(g_originalPersonMt)(engine, seed);
}

namespace {
__attribute__((naked, noinline)) void PersonSeedEntry()
{
    // Five pushes align the stack for the C++ call under the SysV ABI. C++
    // preserves RBX/R12/R15; discard the snapshots and resume the old caller.
    __asm__("push %r15\n\t"
            "push %r12\n\t"
            "push %rbx\n\t"
            "push %rax\n\t"
            "push %rdx\n\t"
            "mov %rsp, %rdx\n\t"
            "call Tpf2mpPersonSeedDispatch\n\t"
            "add $40, %rsp\n\t"
            "ret\n\t");
}
} // namespace

bool Tpf2mpInstallDestinationRng(uintptr_t imageBase, const char* buildId)
{
    if (!imageBase || !buildId || std::strcmp(buildId, kRngBuildId) != 0) return false;
    if (std::memcmp(reinterpret_cast<void*>(imageBase + kRandomRva),
                    kRandomBytes, sizeof(kRandomBytes)) != 0 ||
        std::memcmp(reinterpret_cast<void*>(imageBase + kInclusiveRva),
                    kInclusiveBytes, sizeof(kInclusiveBytes)) != 0) return false;
    g_nativeInclusive = reinterpret_cast<InclusiveRandom>(imageBase + kInclusiveRva);
    // ENDBR64, push rbp, mov rbp/rsp, sub rsp/16, mov rax/fs:[0x28]. These
    // 21 bytes contain no relative operands; the FS canary load is absolute.
    // InstallHook publishes the original trampoline before patching the entry.
    return InstallHook(imageBase + kRandomRva, reinterpret_cast<void*>(DestinationRandom),
                       21, &g_originalRandom);
}

bool Tpf2mpInstallPersonSeeds(uintptr_t imageBase, const char* buildId)
{
    if (!imageBase || !buildId || std::strcmp(buildId, kRngBuildId) != 0) return false;
    if (std::memcmp(reinterpret_cast<void*>(imageBase + kPersonMtRva),
                    kPersonMtBytes, sizeof(kPersonMtBytes)) != 0 ||
        std::memcmp(reinterpret_cast<void*>(imageBase + kPersonSeedWindowRva),
                    kPersonSeedCallBytes, sizeof(kPersonSeedCallBytes)) != 0 ||
        std::memcmp(reinterpret_cast<void*>(imageBase + kArrivalSeedWindowRva),
                    kArrivalSeedCallBytes, sizeof(kArrivalSeedCallBytes)) != 0 ||
        std::memcmp(reinterpret_cast<void*>(imageBase + kIdleSeedWindowRva),
                    kIdleSeedCallBytes, sizeof(kIdleSeedCallBytes)) != 0) return false;
    for (const auto& site : kExtraPersonSeedSites) {
        if (site.windowRva + site.size != site.returnRva ||
            std::memcmp(reinterpret_cast<void*>(imageBase + site.windowRva), site.bytes, site.size) != 0)
            return false;
    }
    g_departureSeedReturn = imageBase + kPersonSeedReturnRva;
    g_arrivalSeedReturn = imageBase + kArrivalSeedReturnRva;
    g_idleSeedReturn = imageBase + kIdleSeedReturnRva;
    g_personImageBase = imageBase;
    // Two position-independent instructions: mov [rdi],esi; mov edx,1. Stop
    // before the original relative jump at +7. InstallHook uses a near relay
    // for the 5-byte entry jump and a trampoline back to that untouched jump.
    return InstallHook(imageBase + kPersonMtRva, reinterpret_cast<void*>(PersonSeedEntry),
                       7, &g_originalPersonMt);
}
