bool Tpf2mpInstallFloatRng(uintptr_t imageBase, const char* buildId)
{
    if (!imageBase || !buildId || std::strcmp(buildId, kFloatBuildId) != 0) return false;
    if (std::memcmp(reinterpret_cast<void*>(imageBase + kFloatCoreRva),
                    kFloatCoreBytes, sizeof(kFloatCoreBytes)) != 0 ||
        std::memcmp(reinterpret_cast<void*>(imageBase + kFloatScaleRva), &kFloatScale, 4) != 0 ||
        std::memcmp(reinterpret_cast<void*>(imageBase + kFloatOneRva), &kFloatOne, 4) != 0) return false;
    // Both cores produce float(rawMT) * 2^-32 with exactly one draw. Native
    // additionally clamps a rounded 1.0 to nextafterf(1,0); Windows keeps 1.0.
    // Remove only that conditional branch, retaining the original MT state,
    // twist, conversion, multiplication and all surrounding float wrappers.
    static constexpr unsigned char nops[] = {0x90, 0x90};
    int error = 0;
    return Tpf2mpCodeWriteSelf(imageBase + kFloatClampRva, nops, sizeof(nops), &error) == TPF2MP_CW_OK;
}
