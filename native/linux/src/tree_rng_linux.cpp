bool Tpf2mpInstallTreeRng(uintptr_t imageBase, const char* buildId)
{
    if (g_treeInstalled) { g_treeStatus = "enabled (already installed)"; return false; }
    if (!imageBase || !buildId || std::strcmp(buildId, kTreeBuildId) != 0) {
        g_treeStatus = "off (unverified image)"; return false;
    }
    if (std::memcmp(reinterpret_cast<void*>(imageBase + kTreeUnitRva), kTreeUnitBytes, sizeof(kTreeUnitBytes)) != 0
        || std::memcmp(reinterpret_cast<void*>(imageBase + kTreeAngleRva), &kTreeAngle, 4) != 0
        || std::memcmp(reinterpret_cast<void*>(imageBase + kTreeUnitScaleRva), &kTreeUnitScale, 4) != 0
        || std::memcmp(reinterpret_cast<void*>(imageBase + kTreeUnitOneRva), &kTreeUnitOne, 4) != 0
        || std::memcmp(reinterpret_cast<void*>(imageBase + kTreeContextRva),
                    kTreeContextBytes, sizeof(kTreeContextBytes)) != 0
        || std::memcmp(reinterpret_cast<void*>(imageBase + kTreeInclusiveRva),
                       kTreeInclusiveBytes, sizeof(kTreeInclusiveBytes)) != 0
        || std::memcmp(reinterpret_cast<void*>(imageBase + kTreeTwistRva),
                       kTreeTwistBytes, sizeof(kTreeTwistBytes)) != 0) {
        g_treeStatus = "off (unverified tree distribution/MT implementation)"; return false;
    }
    g_treeInclusive = reinterpret_cast<TreeInclusive>(imageBase + kTreeInclusiveRva);
    Tpf2mpTreeResume = reinterpret_cast<void*>(imageBase + kTreeResumeRva);
    unsigned char jump[14] = {0xff, 0x25, 0, 0, 0, 0};
    const uintptr_t target = reinterpret_cast<uintptr_t>(TreeRngEntry);
    std::memcpy(jump + 6, &target, sizeof(target));
    int error = 0;
    const bool entryWritten = Tpf2mpCodeWriteSelf(imageBase + kTreeEntryRva,
                                                jump, sizeof(jump), &error) == TPF2MP_CW_OK;
    g_treeInstalled = entryWritten && Tpf2mpCodeWriteSelf(imageBase + kTreeDrawsRva,
        kTreeDrawsBytes, sizeof(kTreeDrawsBytes), &error) == TPF2MP_CW_OK;
    if (g_treeInstalled) {
        g_treeStatus = "enabled at verified tree selection and scale/angle draws";
    } else {
        bool intact = true;
        for (const auto& site : {std::pair<uintptr_t, size_t>{kTreeEntryRva, sizeof(jump)},
                                {kTreeDrawsRva, sizeof(kTreeDrawsBytes)}}) {
            const auto* original = kTreeContextBytes + site.first - kTreeContextRva;
            const auto address = imageBase + site.first;
            if (std::memcmp(reinterpret_cast<void*>(address), original, site.second))
                Tpf2mpCodeWriteSelf(address, original, site.second, &error);
            intact &= !std::memcmp(reinterpret_cast<void*>(address), original, site.second);
        }
        if (intact) {
            g_treeStatus = "off (write failed; original tree selection intact)";
            g_treeInclusive = nullptr;
            Tpf2mpTreeResume = nullptr;
        } else g_treeStatus = "ERROR: tree hook failed and entry is altered";
    }
    return g_treeInstalled;
}

const char* Tpf2mpTreeRngStatus() { return g_treeStatus; }
