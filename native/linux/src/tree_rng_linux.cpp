extern "C" __attribute__((visibility("hidden"), noinline))
void Tpf2mpTreeRngDispatch(TreeRegisters* registers)
{
    registers->rax = WindowsTreeIndex(reinterpret_cast<void*>(registers->r13),
                                     uint32_t(registers->r12));
    // The skipped native block reloads this pointer immediately before its
    // division. Keep the original CDQE/string-selection continuation intact.
    std::memcpy(&registers->rsi,
                reinterpret_cast<void*>(registers->rbp - 0x1830), sizeof(uint64_t));
}

