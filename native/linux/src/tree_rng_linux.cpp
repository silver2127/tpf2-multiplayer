struct TreeRegisters {
    uint64_t r15, r14, r13, r12, rbp, rbx, r11, r10, r9, r8;
    uint64_t rdi, rsi, rdx, rcx, rax, flags;
};
static_assert(sizeof(TreeRegisters) == 128);
static_assert(offsetof(TreeRegisters, rax) == 112);
using TreeInclusive = int32_t (*)(void*, const int32_t*);
TreeInclusive g_treeInclusive = nullptr;
bool g_treeInstalled = false;
