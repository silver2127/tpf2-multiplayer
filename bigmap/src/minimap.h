// The loaded image's address range, for the vtable sanity check.
static bool MinimapImageRange(uintptr_t base, uintptr_t* lo, uintptr_t* hi) {
    const auto dos = reinterpret_cast<const IMAGE_DOS_HEADER*>(base);
    if (!base || dos->e_magic != IMAGE_DOS_SIGNATURE) return false;
    const auto nt = reinterpret_cast<const IMAGE_NT_HEADERS64*>(base + dos->e_lfanew);
    if (nt->Signature != IMAGE_NT_SIGNATURE) return false;
    *lo = base;
    *hi = base + nt->OptionalHeader.SizeOfImage;
    return true;
}

static bool InstallMinimap() {
    if (!g_minimap || g_gog) {
        if (g_minimap) H->log("minimap: Steam 35924 only; OFF");
        SyncGameMinimapScript(false);
        return false;
    }
    if (!MinimapVerifySites()) {
        H->log("minimap: Steam 35924 byte mismatch; OFF");
        SyncGameMinimapScript(false);
        return false;
    }
    const uintptr_t base = H->moduleBase();
    if (!MinimapImageRange(base, &g_minimapImageLo, &g_minimapImageHi)) {
        H->log("minimap: cannot read the game image headers; OFF");
        SyncGameMinimapScript(false);
        return false;
    }
    g_minimapSetImageRaw = reinterpret_cast<MinimapSetImageRawFn>(base + 0x22b4350);
    g_minimapBaseGetVertices = reinterpret_cast<MinimapVerticesFn>(base + 0x33d130);
    // Capture first: the image hook is useless without a game UI to read from.
    uint8_t* thunk = MinimapBuildCaptureThunk(&g_minimapGameUI, &g_minimapCreateMenuTrampoline);
    const bool capture = thunk && H->installHook(base + 0x5a2900, reinterpret_cast<void*>(thunk),
        sizeof kMinimapCreateMenuBytes, &g_minimapCreateMenuTrampoline) != 0;
    const bool image = capture && H->installHook(base + 0x22b4610, reinterpret_cast<void*>(&MinimapSetImagePathDetour),
        sizeof kMinimapSetImagePathBytes, reinterpret_cast<void**>(&g_minimapSetImagePath)) != 0;
    if (!capture || !image) {
        // A lone capture hook only records a pointer; without the script nothing uses it.
        H->log("minimap: hook failed (game UI capture %s, image %s); OFF",
               capture ? "ok" : "FAILED", image ? "ok" : "FAILED");
        SyncGameMinimapScript(false);
        return false;
    }
    const int rc = SyncGameMinimapScript(true);
    const bool ok = rc == MINIMAP_SCRIPT_WRITTEN || rc == MINIMAP_SCRIPT_ALREADY;
    H->log("minimap: %s -- the map button is on the main toolbar in game", ok ? "enabled" : "hooks installed but no script");
    return ok;
}

