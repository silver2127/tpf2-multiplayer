// Steam 35924: an in-game minimap that works on the largest maps.
//
// The picture is not drawn by Lua. The minimap game script
// (mod/minimap/bigmap_minimap.lua, written into res/config/game_script at
// start) calls an ordinary ImageView's setImage() with a token
//
//   bigmap:minimap?x0=<m>&y0=<m>&x1=<m>&y1=<m>&w=<px>&h=<px>[&relief=<k>][&g=<n>]
//
// and the detour on ImageView::SetImage(string) (0x22b4610, the only image
// method Lua can reach) renders that world rectangle from the live terrain and
// uploads it as the image's texture through ImageView::SetImage(raw)
// (0x22b4350), the path the engine's own map preview uses. There is no widget
// per pixel and no line primitive, so the cost is the pixel count, not the map
// size. Every other image path passes straight through after a prefix check.
//
// Heights come from CTerrain::BaseGetVertices (0x33d130), the 65x65 base
// heightmap per tile, which the height-cache pager never touches. The terrain
// is reached the way the UI reaches it: *(CGameUI+0x450) -> vtbl[1] -> +0x20.
// CGameUI is captured by a thunk on CreateConstructionMenu (0x5a2900), which
// runs once per world. Colouring follows the engine's CreateTextureData
// (0x63b9a0): the default climate height ramp, a water depth ramp, a hillshade
// and a 24-direction ambient term.
//
// Reverse engineering: docs/minimap-native-preview.md. Included after H,
// g_gog, ReadWholeFile and WriteWholeFile. Steam only.
