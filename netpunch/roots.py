def ssl_context():
    """The default context (system store, hostname check) plus the ISRG roots."""
    ctx = ssl.create_default_context()
    try:
        ctx.load_verify_locations(cadata=ISRG_ROOTS_PEM)
    except (ssl.SSLError, ValueError):
        pass
    return ctx


def roots_only_context():
    """For tests: trust nothing but the embedded roots (a bare Windows store)."""
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    ctx.verify_mode = ssl.CERT_REQUIRED
    ctx.check_hostname = True
    ctx.load_verify_locations(cadata=ISRG_ROOTS_PEM)
    return ctx
